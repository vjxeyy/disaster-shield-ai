/**
 * Generates supabase/seed.sql from the same TypeScript seed used by demo mode, so both modes
 * start with identical Chennai sample data. Timestamps are written relative to now().
 * Run: npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createSeedState } from "../src/lib/data/seed";

const NOW = new Date();
const s = createSeedState(NOW);

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;
const ts = (iso: string) => {
  const mins = Math.round((NOW.getTime() - new Date(iso).getTime()) / 60000);
  return `now() - interval '${mins} minutes'`;
};
const rows = (table: string, cols: string[], values: string[][]) =>
  values.length ? `insert into public.${table} (${cols.join(", ")}) values\n  ${values.map((v) => `(${v.join(", ")})`).join(",\n  ")};\n` : "";

let sql = `-- =====================================================================
-- RESCURA — SIMULATED Chennai demonstration data
-- Generated by scripts/generate-seed-sql.ts (do not edit by hand).
-- All names, phone numbers, readings, incidents, teams and shelters are fictional samples.
-- Run AFTER supabase/migrations/0001_init.sql.
-- =====================================================================
begin;

truncate public.activity_log, public.rescue_assignments, public.sos_status_events, public.sos_requests,
  public.flood_reports, public.disaster_alerts, public.shelter_facilities, public.shelters,
  public.rainfall_readings cascade;

`;

sql += rows(
  "risk_zones",
  ["id", "name", "lat", "lng", "radius_m", "population", "historical_susceptibility", "elevation_m", "drainage_note"],
  s.zones.map((z) => [q(z.id), q(z.name), q(z.lat), q(z.lng), q(z.radiusM), q(z.population), q(z.historicalSusceptibility), q(z.elevationM), q(z.drainageNote)]),
).replace(";\n", "\non conflict (id) do update set name = excluded.name, lat = excluded.lat, lng = excluded.lng, radius_m = excluded.radius_m,\n  population = excluded.population, historical_susceptibility = excluded.historical_susceptibility,\n  elevation_m = excluded.elevation_m, drainage_note = excluded.drainage_note;\n");

sql += "\n" + rows(
  "rainfall_readings",
  ["zone_id", "recorded_at", "rainfall_24h_mm", "intensity_mm_hr", "source"],
  s.rainfall.map((r) => [q(r.zoneId), ts(r.recordedAt), q(r.rainfall24hMm), q(r.intensityMmHr), q(r.source)]),
);

sql += "\n" + rows(
  "rescue_teams",
  ["id", "name", "agency", "team_type", "base_zone_id", "lat", "lng", "members", "contact", "status", "capabilities"],
  s.teams.map((t) => [q(t.id), q(t.name), q(t.agency), q(t.type), q(t.baseZoneId), q(t.lat), q(t.lng), q(t.members), q(t.contact), q(t.status), arr(t.capabilities)]),
).replace(
  ";\n",
  "\non conflict (id) do update set name = excluded.name, agency = excluded.agency, team_type = excluded.team_type,\n  base_zone_id = excluded.base_zone_id, lat = excluded.lat, lng = excluded.lng, members = excluded.members,\n  contact = excluded.contact, status = excluded.status, capabilities = excluded.capabilities;\n",
);

sql += "\n" + rows(
  "shelters",
  ["id", "name", "address", "zone_id", "lat", "lng", "capacity", "occupied", "status", "contact", "updated_at"],
  s.shelters.map((x) => [q(x.id), q(x.name), q(x.address), q(x.zoneId), q(x.lat), q(x.lng), q(x.capacity), q(x.occupied), q(x.status), q(x.contact), ts(x.updatedAt)]),
);

sql += "\n" + rows(
  "shelter_facilities",
  ["shelter_id", "facility"],
  s.shelters.flatMap((x) => x.facilities.map((f) => [q(x.id), q(f)])),
);

sql += "\n" + rows(
  "disaster_alerts",
  ["id", "title", "message", "level", "zone_ids", "instructions", "issued_at", "issued_by_name", "source", "active"],
  s.alerts.map((a) => [q(a.id), q(a.title), q(a.message), q(a.level), arr(a.zoneIds), arr(a.instructions), ts(a.issuedAt), q(a.issuedByName), q(a.source), q(a.active)]),
);

sql += "\n" + rows(
  "flood_reports",
  ["id", "reporter_name", "zone_id", "road_name", "description", "severity", "water_depth_cm", "lat", "lng", "path", "status", "created_at"],
  s.floodReports.map((r) => [
    q(r.id),
    q(r.reporterName),
    q(r.zoneId),
    q(r.roadName),
    q(r.description),
    q(r.severity),
    q(r.waterDepthCm ?? null),
    q(r.lat),
    q(r.lng),
    r.path ? `${q(JSON.stringify(r.path))}::jsonb` : "null",
    q(r.status),
    ts(r.createdAt),
  ]),
);

// SOS rows (resident links omitted: demo residents are not auth users). The insert trigger
// creates each "submitted" event; later events are inserted below.
sql += "\n" + rows(
  "sos_requests",
  ["id", "reference", "name", "phone", "emergency_type", "urgency", "description", "people_count", "zone_id", "landmark", "lat", "lng", "status", "assigned_team_id", "created_at", "updated_at"],
  s.sos.map((x) => [
    q(x.id),
    q(x.reference),
    q(x.name),
    q(x.phone),
    q(x.emergencyType),
    q(x.urgency),
    q(x.description),
    q(x.peopleCount),
    q(x.zoneId),
    q(x.landmark),
    q(x.lat),
    q(x.lng),
    q(x.status),
    q(x.assignedTeamId ?? null),
    ts(x.createdAt),
    ts(x.updatedAt),
  ]),
);
sql += `
update public.sos_status_events e set created_at = s.created_at
  from public.sos_requests s where e.sos_id = s.id and e.status = 'submitted';
select setval('public.sos_reference_seq', ${Math.max(...s.sos.map((x) => Number(x.reference.replace(/\D/g, ""))))});
`;

sql += "\n" + rows(
  "sos_status_events",
  ["sos_id", "status", "note", "actor_name", "created_at"],
  s.sosEvents.filter((e) => e.status !== "submitted").map((e) => [q(e.sosId), q(e.status), q(e.note), q(e.actorName), ts(e.createdAt)]),
);

sql += "\n" + rows(
  "rescue_assignments",
  ["sos_id", "team_id", "assigned_by_name", "assigned_at", "status", "completed_at"],
  s.assignments.map((a) => [q(a.sosId), q(a.teamId), q(a.assignedByName), ts(a.assignedAt), q(a.status), a.completedAt ? ts(a.completedAt) : "null"]),
);

sql += "\n" + rows(
  "activity_log",
  ["type", "message", "zone_id", "severity", "created_at"],
  s.activity.filter((a) => a.type !== "sos").map((a) => [q(a.type), q(a.message), q(a.zoneId ?? null), q(a.severity), ts(a.createdAt)]),
);

sql += `
commit;

-- After creating accounts through the app's sign-up form, promote demo staff, e.g.:
--   update public.profiles set role = 'admin' where email = 'you@example.com';
--   update public.profiles set role = 'official' where email = 'official@example.com';
--   update public.profiles set role = 'rescue', team_id = 'team-1' where email = 'rescue@example.com';
`;

const out = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, sql, "utf8");
console.log(`Wrote ${out} (${sql.length.toLocaleString()} chars)`);
